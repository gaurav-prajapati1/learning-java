package literals;

public class literal {
    public static void main(String[] args) {
         byte age = 34;  // Here 34 is integer-literal
         int age2 = 20;  // Here 20 is integer-literal   
         short age3 = 30;// Here 30 is the integer-literal
         long agelong = 2337374774747l; // Here 2337374774747l is the long-literal
         char ch = 'G';  // Here 'G' is character literals 
         float f1 = 3.9f; //by default it take decimal value in double . we use f to tell this is float number and this is the float literal

        double d1 = 3.14; // Here this is the double literal
        boolean a = true;
        String str = "Gaurav";
        // Here is print functions 
         System.out.println(age); 
         System.out.println(ch);
         System.out.println(f1);
         System.out.println(d1);
         System.out.println(a);
         System.out.println(age2);
         System.out.println(age3);
         System.out.println(agelong);
         System.out.println(str);


    }
    
}
